-- Esquema PostgreSQL del corte vertical en Supabase (semana 15).
-- Se instala en el esquema independiente aqsis para no tocar public.
-- equivalente a schema.sql, con los mismos índices y reglas RN-22/RN-03.

CREATE SCHEMA IF NOT EXISTS aqsis;

DROP TABLE IF EXISTS aqsis.fotografia;
DROP TABLE IF EXISTS aqsis.mascota;
DROP TABLE IF EXISTS aqsis.usuario;
DROP TABLE IF EXISTS aqsis.refugio;

CREATE TABLE aqsis.refugio (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              TEXT NOT NULL CHECK (char_length(nombre) BETWEEN 3 AND 120),
    localidad           TEXT NOT NULL,
    estado_verificacion TEXT NOT NULL DEFAULT 'pendiente'
        CHECK (estado_verificacion IN ('pendiente', 'verificado', 'rechazado'))
);

CREATE TABLE aqsis.usuario (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario  TEXT NOT NULL UNIQUE CHECK (char_length(nombre_usuario) BETWEEN 3 AND 80),
    contrasena_hash TEXT NOT NULL,
    rol             TEXT NOT NULL CHECK (rol IN ('refugio', 'adoptante', 'admin')),
    refugio_id      INTEGER REFERENCES aqsis.refugio(id) ON DELETE SET NULL,
    activo          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE aqsis.mascota (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refugio_id               INTEGER NOT NULL
        REFERENCES aqsis.refugio(id) ON DELETE RESTRICT,
    nombre                   TEXT NOT NULL CHECK (char_length(nombre) BETWEEN 1 AND 60),
    raza                     TEXT,
    especie                  TEXT NOT NULL CHECK (especie IN ('perro', 'gato')),
    edad_meses               INTEGER NOT NULL CHECK (edad_meses BETWEEN 0 AND 300),
    tamano                   TEXT NOT NULL CHECK (tamano IN ('pequeno', 'mediano', 'grande')),
    nivel_energia            TEXT NOT NULL CHECK (nivel_energia IN ('baja', 'media', 'alta')),
    experiencia_requerida    TEXT NOT NULL CHECK (experiencia_requerida IN ('ninguna', 'basica', 'amplia')),
    apta_con_menores         INTEGER NOT NULL CHECK (apta_con_menores IN (0, 1)),
    apta_con_mascotas        INTEGER NOT NULL CHECK (apta_con_mascotas IN (0, 1)),
    historial_salud          TEXT,
    historial_comportamiento TEXT,
    estado                   TEXT NOT NULL DEFAULT 'incompleta'
        CHECK (estado IN ('incompleta', 'disponible', 'adoptada', 'baja')),
    fecha_publicacion        DATE NOT NULL,
    creado_en                TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Índice que soporta el orden y el filtro principal del catálogo (RF-34).
CREATE INDEX idx_mascota_catalogo
    ON aqsis.mascota (estado, fecha_publicacion, id);

-- Índice de apoyo para los filtros opcionales del catálogo (RF-34).
CREATE INDEX idx_mascota_filtros
    ON aqsis.mascota (especie, tamano, edad_meses);

CREATE TABLE aqsis.fotografia (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mascota_id INTEGER NOT NULL REFERENCES aqsis.mascota(id) ON DELETE CASCADE,
    archivo    TEXT NOT NULL,
    orden      INTEGER NOT NULL CHECK (orden BETWEEN 1 AND 5),
    UNIQUE (mascota_id, orden)
);

CREATE INDEX idx_fotografia_mascota
    ON aqsis.fotografia (mascota_id, orden);

-- RN-22: máximo 5 fotografías por ficha.
CREATE OR REPLACE FUNCTION aqsis.verificar_max_fotos()
RETURNS trigger AS $$
BEGIN
    IF (SELECT COUNT(*) FROM aqsis.fotografia WHERE mascota_id = NEW.mascota_id) >= 5 THEN
        RAISE EXCEPTION 'MAX_FOTOS: una ficha admite maximo 5 fotografias';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_max_fotos ON aqsis.fotografia;
CREATE TRIGGER trg_max_fotos
BEFORE INSERT ON aqsis.fotografia
FOR EACH ROW EXECUTE FUNCTION aqsis.verificar_max_fotos();

-- RN-22: una ficha sin fotografía no puede pasar a disponible.
CREATE OR REPLACE FUNCTION aqsis.verificar_disponible_con_foto()
RETURNS trigger AS $$
BEGIN
    IF NEW.estado = 'disponible'
       AND NOT EXISTS (SELECT 1 FROM aqsis.fotografia WHERE mascota_id = NEW.id) THEN
        RAISE EXCEPTION 'FICHA_INCOMPLETA: se requiere al menos una fotografia';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_disponible_con_foto ON aqsis.mascota;
CREATE TRIGGER trg_disponible_con_foto
BEFORE UPDATE OF estado ON aqsis.mascota
FOR EACH ROW EXECUTE FUNCTION aqsis.verificar_disponible_con_foto();

-- RN-03: solo un refugio verificado puede publicar.
CREATE OR REPLACE FUNCTION aqsis.verificar_disponible_refugio_verificado()
RETURNS trigger AS $$
BEGIN
    IF NEW.estado = 'disponible'
       AND NOT EXISTS (
           SELECT 1 FROM aqsis.refugio
           WHERE id = NEW.refugio_id AND estado_verificacion = 'verificado'
       ) THEN
        RAISE EXCEPTION 'REFUGIO_NO_VERIFICADO: el refugio debe estar verificado';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_disponible_refugio_verificado ON aqsis.mascota;
CREATE TRIGGER trg_disponible_refugio_verificado
BEFORE UPDATE OF estado ON aqsis.mascota
FOR EACH ROW EXECUTE FUNCTION aqsis.verificar_disponible_refugio_verificado();
